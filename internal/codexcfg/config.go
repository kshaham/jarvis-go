// Package codexcfg renders and writes the per-agent ~/.codex/config.toml
// (CODEX_HOME) used to run an OpenAI Codex CLI agent under jarvis.
//
// The shape here is the one verified to work against the OpenAI Responses
// API during the Phase-0 spike: a custom [model_providers.<id>] block with
// env_key (Bearer from an env var) + requires_openai_auth=false, because the
// built-in `openai` provider does NOT bearer-auth from OPENAI_API_KEY in
// headless `codex exec` without `codex login`. The same block works for both
// the official OpenAI API (base_url=https://api.openai.com/v1) and an
// internal OpenAI-compatible endpoint — the endpoint MUST speak the Responses
// API (wire_api="chat" was removed in Codex >= 0.99).
package codexcfg

import (
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strings"
)

// MCPServer is a stdio MCP server entry, re-serialized from the same logical
// set jarvis passes to Claude (jarvis-mcp, codegraph, context7, …) into the
// Codex [mcp_servers.<name>] TOML shape.
type MCPServer struct {
	Command string
	Args    []string
	Env     map[string]string
}

// Provider describes a custom [model_providers.<id>] block. Nil on a Config
// means "use the built-in openai provider" (ChatGPT-subscription auth via
// `codex login`); non-nil means API-key/custom-endpoint Bearer auth.
type Provider struct {
	ID                 string // table id, e.g. "jarvis-openai"
	Name               string // display name
	BaseURL            string // e.g. https://api.openai.com/v1 or the internal proxy
	EnvKey             string // NAME of the env var holding the key (sent as Bearer)
	WireAPI            string // "responses" (the only supported value as of Codex >= 0.99)
	RequiresOpenAIAuth bool   // false for non-OpenAI gateways (skip sk- prefix validation)
}

// Config is the inputs needed to render a Codex config.toml.
type Config struct {
	Model           string // e.g. "gpt-5.5"
	ReasoningEffort string // minimal|low|medium|high|xhigh ("" omits the key)
	SandboxMode     string // e.g. "danger-full-access" (we run in a container)
	ApprovalPolicy  string // e.g. "never"
	Provider        *Provider
	MCPServers      map[string]MCPServer

	// WebSearch sets the top-level `web_search` mode: disabled|cached|live
	// (Codex 0.135 — the search_tool feature flag is gone; this replaces it).
	// "live" lets agents fetch current docs/APIs/errors; "" omits the key
	// (Codex defaults to "live" under a full-access sandbox).
	WebSearch string

	// Personality sets the top-level `personality`: none|friendly|pragmatic.
	// jarvis uses "none" so the per-member persona it injects in the prompt
	// drives voice, not Codex's built-in persona layer. "" omits the key.
	Personality string

	// AgentsMaxThreads / AgentsMaxDepth bound Codex's stable multi_agent
	// fan-out (the [agents] table: spawn_agent/wait_agent/... tools). 0 omits
	// the field (Codex defaults: max_threads=6, max_depth=1).
	AgentsMaxThreads int
	AgentsMaxDepth   int
}

// MapReasoningEffort converts jarvis's effort tier (low|medium|high|max) to
// Codex's model_reasoning_effort scale (minimal|low|medium|high|xhigh). jarvis
// "max" maps to Codex "xhigh" (its closest analog). Unknown/empty returns "".
func MapReasoningEffort(jarvisEffort string) string {
	switch strings.ToLower(strings.TrimSpace(jarvisEffort)) {
	case "minimal":
		return "minimal"
	case "low":
		return "low"
	case "medium":
		return "medium"
	case "high":
		return "high"
	case "max", "xhigh":
		return "xhigh"
	default:
		return ""
	}
}

// tomlStr quotes + escapes a TOML basic string.
func tomlStr(s string) string {
	r := strings.NewReplacer(`\`, `\\`, `"`, `\"`, "\n", `\n`, "\t", `\t`)
	return `"` + r.Replace(s) + `"`
}

// tomlArray renders a string array as a single-line TOML array.
func tomlArray(items []string) string {
	quoted := make([]string, len(items))
	for i, it := range items {
		quoted[i] = tomlStr(it)
	}
	return "[" + strings.Join(quoted, ", ") + "]"
}

// tomlInlineTable renders a map as a sorted single-line TOML inline table:
// { "K" = "V", … }. Sorted for deterministic output (stable tests + diffs).
func tomlInlineTable(m map[string]string) string {
	if len(m) == 0 {
		return "{}"
	}
	keys := make([]string, 0, len(m))
	for k := range m {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	parts := make([]string, 0, len(keys))
	for _, k := range keys {
		parts = append(parts, fmt.Sprintf("%s = %s", tomlStr(k), tomlStr(m[k])))
	}
	return "{ " + strings.Join(parts, ", ") + " }"
}

// Render produces the config.toml text for the given Config.
func Render(c Config) string {
	var b strings.Builder
	b.WriteString("# Generated by jarvis — per-agent Codex config. Do not edit by hand.\n\n")
	if c.Model != "" {
		fmt.Fprintf(&b, "model = %s\n", tomlStr(c.Model))
	}
	if c.Provider != nil {
		fmt.Fprintf(&b, "model_provider = %s\n", tomlStr(c.Provider.ID))
	}
	if c.ReasoningEffort != "" {
		fmt.Fprintf(&b, "model_reasoning_effort = %s\n", tomlStr(c.ReasoningEffort))
	}
	if c.ApprovalPolicy != "" {
		fmt.Fprintf(&b, "approval_policy = %s\n", tomlStr(c.ApprovalPolicy))
	}
	if c.SandboxMode != "" {
		fmt.Fprintf(&b, "sandbox_mode = %s\n", tomlStr(c.SandboxMode))
	}
	if c.WebSearch != "" {
		fmt.Fprintf(&b, "web_search = %s\n", tomlStr(c.WebSearch))
	}
	if c.Personality != "" {
		fmt.Fprintf(&b, "personality = %s\n", tomlStr(c.Personality))
	}

	// [agents] bounds for Codex's multi-agent fan-out. Written before the
	// other tables so all top-level keys above precede every [table] (TOML).
	if c.AgentsMaxThreads > 0 || c.AgentsMaxDepth > 0 {
		b.WriteString("\n[agents]\n")
		if c.AgentsMaxThreads > 0 {
			fmt.Fprintf(&b, "max_threads = %d\n", c.AgentsMaxThreads)
		}
		if c.AgentsMaxDepth > 0 {
			fmt.Fprintf(&b, "max_depth = %d\n", c.AgentsMaxDepth)
		}
	}

	if c.Provider != nil {
		p := c.Provider
		wire := p.WireAPI
		if wire == "" {
			wire = "responses"
		}
		fmt.Fprintf(&b, "\n[model_providers.%s]\n", p.ID)
		if p.Name != "" {
			fmt.Fprintf(&b, "name = %s\n", tomlStr(p.Name))
		}
		fmt.Fprintf(&b, "base_url = %s\n", tomlStr(p.BaseURL))
		if p.EnvKey != "" {
			fmt.Fprintf(&b, "env_key = %s\n", tomlStr(p.EnvKey))
		}
		fmt.Fprintf(&b, "wire_api = %s\n", tomlStr(wire))
		fmt.Fprintf(&b, "requires_openai_auth = %t\n", p.RequiresOpenAIAuth)
	}

	// [mcp_servers.<name>] blocks, sorted by name for deterministic output.
	if len(c.MCPServers) > 0 {
		names := make([]string, 0, len(c.MCPServers))
		for n := range c.MCPServers {
			names = append(names, n)
		}
		sort.Strings(names)
		for _, n := range names {
			s := c.MCPServers[n]
			fmt.Fprintf(&b, "\n[mcp_servers.%s]\n", n)
			fmt.Fprintf(&b, "command = %s\n", tomlStr(s.Command))
			if len(s.Args) > 0 {
				fmt.Fprintf(&b, "args = %s\n", tomlArray(s.Args))
			}
			if len(s.Env) > 0 {
				fmt.Fprintf(&b, "env = %s\n", tomlInlineTable(s.Env))
			}
		}
	}

	return b.String()
}

// Write renders the config and writes it atomically to
// <codexHome>/config.toml, creating codexHome (0700) if needed. Returns the
// config.toml path. codexHome is the per-agent CODEX_HOME.
func Write(codexHome string, c Config) (string, error) {
	if codexHome == "" {
		return "", fmt.Errorf("codexcfg: empty CODEX_HOME")
	}
	if err := os.MkdirAll(codexHome, 0o700); err != nil {
		return "", fmt.Errorf("codexcfg: mkdir %s: %w", codexHome, err)
	}
	final := filepath.Join(codexHome, "config.toml")
	tmp := final + ".tmp"
	if err := os.WriteFile(tmp, []byte(Render(c)), 0o600); err != nil {
		return "", fmt.Errorf("codexcfg: write %s: %w", tmp, err)
	}
	if err := os.Rename(tmp, final); err != nil {
		return "", fmt.Errorf("codexcfg: rename %s: %w", final, err)
	}
	return final, nil
}
