package office

import (
	"fmt"
	"os"
	"path/filepath"
	"strings"
)

// R2.3 · per-session statusline + output-style generators. Surfaces
// office state inside Claude's own terminal so operators can tell
// from the prompt whether the team is paused, who they are, what
// their current task is, etc.
//
// The statusline is a small shell script that curls jarvis's
// /api/office/agent/statusline endpoint and prints one line. The
// output style is a static JSON file (Claude's documented format)
// that references the script.

// statuslineScriptName is the per-agent shell script. Lives in the
// worktree's .claude/ so it's path-relative for Claude.
const statuslineScriptName = "statusline.sh"

// outputStyleFileName is what Claude looks for in
// .claude/output-style.json.
const outputStyleFileName = "output-style.json"

// StatusLineParams describes the per-session knobs the generated
// statusline script needs. SessionID gets baked into the URL path so
// the endpoint can resolve which agent to render. DaemonURL is the
// reachable address of jarvis from inside the spawned `claude`
// process (typically http://127.0.0.1:<port>).
type StatusLineParams struct {
	SessionID string
	DaemonURL string
	// AuthEnvVar is the env-var name the script reads to attach the
	// agent token via Authorization: Bearer. Same convention as the
	// hooks settings — defaults to JARVIS_AGENT_TOKEN.
	AuthEnvVar string
}

// WriteStatusLine installs the per-session statusline + output-style
// into <cwd>/.claude/. Idempotent and marker-stamped like the other
// claudefiles helpers; operator-authored files are not overwritten.
//
// On any error the function returns it; caller decides whether the
// failure is fatal. The script + output-style are independent — a
// failure on one doesn't prevent the other.
func WriteStatusLine(cwd string, p StatusLineParams) error {
	if cwd == "" {
		return ErrNoCwd
	}
	if p.SessionID == "" {
		return fmt.Errorf("office: StatusLineParams.SessionID is required")
	}
	if p.DaemonURL == "" {
		return fmt.Errorf("office: StatusLineParams.DaemonURL is required")
	}
	authVar := p.AuthEnvVar
	if authVar == "" {
		authVar = "JARVIS_AGENT_TOKEN"
	}

	dir := filepath.Join(cwd, ".claude")
	if err := os.MkdirAll(dir, 0o755); err != nil {
		return fmt.Errorf("office: mkdir .claude: %w", err)
	}

	// Script first.
	scriptPath := filepath.Join(dir, statuslineScriptName)
	if existing, err := os.ReadFile(scriptPath); err == nil && !isJarvisStatusLine(existing) {
		// Operator-authored statusline — leave alone.
	} else if err != nil && !os.IsNotExist(err) {
		return fmt.Errorf("office: read existing statusline: %w", err)
	} else {
		script := renderStatusLineScript(p, authVar)
		if err := writeFileAtomic0755(scriptPath, []byte(script)); err != nil {
			return err
		}
	}

	// Output-style JSON. Tiny doc that points at the script + sets a
	// short rendering preset Claude understands. We use the
	// "command"-driven statusline style documented for ~/.claude/.
	stylePath := filepath.Join(dir, outputStyleFileName)
	if existing, err := os.ReadFile(stylePath); err == nil && !isJarvisOutputStyle(existing) {
		// Operator-authored — leave alone.
	} else if err != nil && !os.IsNotExist(err) {
		return fmt.Errorf("office: read existing output-style: %w", err)
	} else {
		style := renderOutputStyle()
		if err := writeFileAtomic0644(stylePath, []byte(style)); err != nil {
			return err
		}
	}
	return nil
}

// RemoveStatusLine cleans up the per-session script + output-style on
// teardown. Same operator-protection semantics as elsewhere.
func RemoveStatusLine(cwd string) error {
	for _, name := range []string{statuslineScriptName, outputStyleFileName} {
		path := filepath.Join(cwd, ".claude", name)
		data, err := os.ReadFile(path)
		if err != nil {
			if os.IsNotExist(err) {
				continue
			}
			return err
		}
		if name == statuslineScriptName && !isJarvisStatusLine(data) {
			continue
		}
		if name == outputStyleFileName && !isJarvisOutputStyle(data) {
			continue
		}
		_ = os.Remove(path)
	}
	return nil
}

// renderStatusLineScript builds the per-session shell script. The
// script does one HTTP fetch to jarvis's statusline endpoint and
// prints its output verbatim. Falls back to a static line if the
// daemon is unreachable so the operator never sees a blank statusline.
func renderStatusLineScript(p StatusLineParams, authVar string) string {
	url := strings.TrimRight(p.DaemonURL, "/") +
		"/api/office/agent/statusline?sessionId=" + p.SessionID
	return `#!/bin/sh
# ` + jarvisStatusLineMarker + `
# Generated by jarvis-office. Edit this file to take it over -- the
# marker line above is what lets jarvis know to leave it alone.
set -e
TOKEN="${` + authVar + `:-}"
if [ -z "$TOKEN" ]; then
  printf '[office] (no token)\n'
  exit 0
fi
curl --max-time 1 --silent --show-error \
  -H "Authorization: Bearer $TOKEN" \
  ` + shellQuote(url) + ` 2>/dev/null || printf '[office] (offline)\n'
`
}

// renderOutputStyle returns the static JSON Claude reads to find the
// statusline script. The shape matches what Claude Code documents for
// .claude/output-style.json — a single "statusLine" object pointing at
// a command. Anchored to "command" so operators can swap their own
// command in without touching jarvis's logic.
func renderOutputStyle() string {
	return `{
  "_jarvisGenerated": true,
  "statusLine": {
    "type": "command",
    "command": "sh ${CLAUDE_PROJECT_DIR}/.claude/` + statuslineScriptName + `"
  }
}
`
}

// Marker lines are kept distinct between the shell script (uses a
// comment) and the JSON file (uses a sentinel key) so each file can be
// authored by jarvis without clobbering the other format.
const jarvisStatusLineMarker = "jarvis-office-statusline-v1"

func isJarvisStatusLine(data []byte) bool {
	return strings.Contains(string(data), jarvisStatusLineMarker)
}

func isJarvisOutputStyle(data []byte) bool {
	return strings.Contains(string(data), `"_jarvisGenerated": true`)
}

// shellQuote single-quotes a string for safe inclusion in a /bin/sh
// script. URL fragments shouldn't contain single quotes but defensive
// quoting prevents accidental command injection if a future call site
// passes anything user-supplied.
func shellQuote(s string) string {
	return "'" + strings.ReplaceAll(s, "'", "'\\''") + "'"
}

func writeFileAtomic0755(path string, data []byte) error {
	tmp := path + ".tmp"
	if err := os.WriteFile(tmp, data, 0o755); err != nil {
		return fmt.Errorf("office: write tmp: %w", err)
	}
	if err := os.Rename(tmp, path); err != nil {
		os.Remove(tmp)
		return fmt.Errorf("office: rename %s: %w", path, err)
	}
	return nil
}

func writeFileAtomic0644(path string, data []byte) error {
	tmp := path + ".tmp"
	if err := os.WriteFile(tmp, data, 0o644); err != nil {
		return fmt.Errorf("office: write tmp: %w", err)
	}
	if err := os.Rename(tmp, path); err != nil {
		os.Remove(tmp)
		return fmt.Errorf("office: rename %s: %w", path, err)
	}
	return nil
}
